"""Generate interface docs and snapshots from the server itself (DESIGN.md decisions 21, 32).

Outputs, all derived from what an MCP client actually receives (``tools/list``,
``resources/list``, ``resources/templates/list``, ``prompts/list``):

- the tool table in ``README.md``, between ``README_START`` and ``README_END``;
- the resource and prompt tables in ``README.md``, between ``REFERENCE_START`` and
  ``REFERENCE_END``;
- ``docs/TOOLS.md``, a full reference (tools with parameters and return fields, then resources
  and prompts);
- ``tests/snapshots/tool_schemas.json``, every tool's description and input/output schemas;
- ``tests/snapshots/reference_surface.json``, every resource, template and prompt.

``scripts/gen_tool_docs.py`` writes them; ``check()`` lists the ones that are stale, and a test
fails on any, so an interface change cannot land without its docs and snapshot.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from fastmcp import Client

from econ_gateway import prompts, resources
from econ_gateway.config import AVAILABLE_TOOLSETS, PROJECT_ROOT
from econ_gateway.services.upstream import LiveUpstream
from econ_gateway.toolsets import TOOLSET_BUILDERS

README_PATH = PROJECT_ROOT / "README.md"
TOOLS_DOC_PATH = PROJECT_ROOT / "docs" / "TOOLS.md"
SNAPSHOT_PATH = PROJECT_ROOT / "tests" / "snapshots" / "tool_schemas.json"
REFERENCE_SNAPSHOT_PATH = PROJECT_ROOT / "tests" / "snapshots" / "reference_surface.json"
README_START = "<!-- tools:start (generated by scripts/gen_tool_docs.py; do not edit by hand) -->"
README_END = "<!-- tools:end -->"
REFERENCE_START = (
    "<!-- reference:start (generated by scripts/gen_tool_docs.py; do not edit by hand) -->"
)
REFERENCE_END = "<!-- reference:end -->"


@dataclass(frozen=True)
class ToolInfo:
    """One tool as a client sees it.

    Attributes:
        toolset: Toolset that provides it.
        name: Tool name.
        description: Full description (the tool's docstring).
        input_schema: JSON Schema of the arguments.
        output_schema: JSON Schema of the structured result.
        annotations: MCP behaviour hints.
    """

    toolset: str
    name: str
    description: str
    input_schema: dict[str, Any]
    output_schema: dict[str, Any]
    annotations: dict[str, Any]

    @property
    def summary(self) -> str:
        """First line of the description."""
        return self.description.strip().splitlines()[0] if self.description else ""


async def collect_tools() -> list[ToolInfo]:
    """List every tool of every toolset, in toolset order then server order.

    Tools are only listed, never called, so the real upstream is never contacted.
    """
    upstream = LiveUpstream()  # construction is lazy: no files or network touched
    found: list[ToolInfo] = []
    for toolset, build in TOOLSET_BUILDERS.items():
        async with Client(build(upstream)) as client:
            for tool in await client.list_tools():
                annotations = (
                    tool.annotations.model_dump(exclude_none=True) if tool.annotations else {}
                )
                found.append(
                    ToolInfo(
                        toolset=toolset,
                        name=tool.name,
                        description=tool.description or "",
                        input_schema=dict(tool.input_schema),
                        output_schema=dict(tool.output_schema or {}),
                        annotations=annotations,
                    )
                )
    return found


@dataclass(frozen=True)
class ReferenceInfo:
    """One resource, resource template or prompt as a client sees it.

    Attributes:
        kind: ``resource``, ``template`` or ``prompt``.
        name: Registered name.
        uri: URI or URI template (``None`` for prompts).
        description: Full description.
        mime_type: Content type of a resource (``None`` for prompts).
        arguments: Prompt arguments as ``(name, required, description)``.
    """

    kind: str
    name: str
    uri: str | None
    description: str
    mime_type: str | None = None
    arguments: tuple[tuple[str, bool, str], ...] = ()

    @property
    def summary(self) -> str:
        """First line of the description."""
        return self.description.strip().splitlines()[0] if self.description else ""


async def collect_reference() -> list[ReferenceInfo]:
    """List resources, templates and prompts with every toolset enabled (nothing is read)."""
    found: list[ReferenceInfo] = []
    toolsets = list(AVAILABLE_TOOLSETS)
    async with Client(resources.build(LiveUpstream(), toolsets)) as client:
        for res in await client.list_resources():
            found.append(
                ReferenceInfo(
                    "resource", res.name, str(res.uri), res.description or "", res.mime_type
                )
            )
        for tpl in await client.list_resource_templates():
            found.append(
                ReferenceInfo(
                    "template", tpl.name, tpl.uri_template, tpl.description or "", tpl.mime_type
                )
            )
    async with Client(prompts.build(toolsets)) as client:
        for prompt in await client.list_prompts():
            arguments = tuple(
                (a.name, bool(a.required), a.description or "") for a in prompt.arguments or []
            )
            found.append(
                ReferenceInfo(
                    "prompt", prompt.name, None, prompt.description or "", None, arguments
                )
            )
    return found


# ---------------------------------------------------------------- rendering helpers


def type_name(schema: dict[str, Any]) -> str:
    """Compact, readable type for a JSON Schema fragment (``str | null``, ``list[str]``...)."""
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "const" in schema:
        return f"`{schema['const']}`"
    if "anyOf" in schema:
        return " \\| ".join(type_name(s) for s in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        items = schema.get("items")
        if isinstance(items, dict):
            return f"list[{type_name(items)}]"
        prefix = schema.get("prefixItems", [])
        return f"[{', '.join(type_name(s) for s in prefix)}]" if prefix else "list"
    if kind == "object":
        return str(schema.get("title", "object"))
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}.get(
        str(kind), str(kind or schema.get("title", "any"))
    )


def _cell(text: str) -> str:
    """Make text safe for a one-line markdown table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def _inputs_summary(tool: ToolInfo) -> str:
    required = set(tool.input_schema.get("required", []))
    names = [
        f"`{n}`" + ("*" if n in required else "") for n in tool.input_schema.get("properties", {})
    ]
    return ", ".join(names)


def render_readme_table(tools: list[ToolInfo]) -> str:
    """The README tool table (inputs marked * are required)."""
    lines = [
        "| Toolset | Tool | What it does | Inputs (* required) |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {t.toolset} | `{t.name}` | {_cell(t.summary)} | {_inputs_summary(t)} |" for t in tools
    ]
    return "\n".join(lines)


def render_reference_tables(items: list[ReferenceInfo]) -> str:
    """README tables of resources (with templates) and prompts."""
    lines = ["| Resource | What it holds |", "|---|---|"]
    lines += [f"| `{i.uri}` | {_cell(i.summary)} |" for i in items if i.kind != "prompt"]
    lines += ["", "| Prompt | What it asks | Arguments (* required) |", "|---|---|---|"]
    for item in (i for i in items if i.kind == "prompt"):
        args = ", ".join(f"`{n}`" + ("*" if required else "") for n, required, _ in item.arguments)
        lines.append(f"| `{item.name}` | {_cell(item.summary)} | {args} |")
    return "\n".join(lines)


def _render_reference_doc(items: list[ReferenceInfo]) -> list[str]:
    """Resource and prompt sections of ``docs/TOOLS.md``."""
    parts = ["", "## Resources", "", "Read-only documents a client attaches as context."]
    for item in (i for i in items if i.kind != "prompt"):
        parts += ["", f"### `{item.uri}`", "", f"_{item.mime_type}_", "", item.description.strip()]
    parts += ["", "## Prompts", "", "Question templates a user picks in their client."]
    for item in (i for i in items if i.kind == "prompt"):
        parts += ["", f"### `{item.name}`", "", item.description.strip(), ""]
        parts += [
            f"- `{n}` ({'required' if required else 'optional'}): {_cell(text)}"
            for n, required, text in item.arguments
        ]
    return parts


def _demote_headings(text: str) -> str:
    """Tool docstrings use ``##`` sections; nest them under the tool's ``###`` heading."""
    return re.sub(r"(?m)^## ", "#### ", text.strip())


def _parameters_table(tool: ToolInfo) -> str:
    properties: dict[str, Any] = tool.input_schema.get("properties", {})
    if not properties:
        return "_No parameters._"
    required = set(tool.input_schema.get("required", []))
    lines = ["| Parameter | Type | Required | Default | Description |", "|---|---|---|---|---|"]
    for name, schema in properties.items():
        default = json.dumps(schema["default"]) if "default" in schema else ""
        lines.append(
            f"| `{name}` | {type_name(schema)} | {'yes' if name in required else 'no'} | "
            f"{_cell(default)} | {_cell(schema.get('description', ''))} |"
        )
    return "\n".join(lines)


def _returns_list(tool: ToolInfo) -> str:
    properties: dict[str, Any] = tool.output_schema.get("properties", {})
    if not properties:
        return "_Unstructured._"
    return "\n".join(f"- `{name}`: {type_name(schema)}" for name, schema in properties.items())


def render_tools_doc(tools: list[ToolInfo], reference: list[ReferenceInfo]) -> str:
    """Full reference page: tools grouped by toolset, then resources and prompts."""
    parts = [
        "# Tool, resource and prompt reference",
        "",
        "_Generated by `scripts/gen_tool_docs.py` from the server's own tool definitions. "
        "Do not edit by hand._",
        "",
        render_readme_table(tools),
    ]
    for toolset in dict.fromkeys(t.toolset for t in tools):
        parts += ["", f"## `{toolset}` toolset"]
        for tool in (t for t in tools if t.toolset == toolset):
            parts += [
                "",
                f"### `{tool.name}`",
                "",
                _demote_headings(tool.description),
                "",
                "#### Parameters",
                "",
                _parameters_table(tool),
                "",
                "#### Returns",
                "",
                _returns_list(tool),
            ]
    parts += _render_reference_doc(reference)
    return "\n".join(parts) + "\n"


def render_snapshot(tools: list[ToolInfo]) -> str:
    """Stable JSON of every tool's interface, for diff review."""
    data = {
        t.name: {
            "toolset": t.toolset,
            "description": t.description,
            "annotations": t.annotations,
            "input_schema": t.input_schema,
            "output_schema": t.output_schema,
        }
        for t in tools
    }
    return json.dumps(data, indent=1, sort_keys=True) + "\n"


def render_reference_snapshot(items: list[ReferenceInfo]) -> str:
    """Stable JSON of every resource, template and prompt, for diff review."""
    data = {
        f"{i.kind}:{i.uri or i.name}": {
            "name": i.name,
            "description": i.description,
            "mime_type": i.mime_type,
            "arguments": [list(a) for a in i.arguments],
        }
        for i in items
    }
    return json.dumps(data, indent=1, sort_keys=True) + "\n"


def _replace_readme_section(readme: str, table: str, start_marker: str, end_marker: str) -> str:
    start, end = readme.find(start_marker), readme.find(end_marker)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"README.md must contain the markers {start_marker!r} and {end_marker!r}.")
    return readme[: start + len(start_marker)] + "\n" + table + "\n" + readme[end:]


# ---------------------------------------------------------------- write / check


async def render_all() -> dict[Path, str]:
    """Expected content of every generated file."""
    tools = await collect_tools()
    reference = await collect_reference()
    readme = README_PATH.read_text(encoding="utf-8")
    readme = _replace_readme_section(readme, render_readme_table(tools), README_START, README_END)
    readme = _replace_readme_section(
        readme, render_reference_tables(reference), REFERENCE_START, REFERENCE_END
    )
    return {
        README_PATH: readme,
        TOOLS_DOC_PATH: render_tools_doc(tools, reference),
        SNAPSHOT_PATH: render_snapshot(tools),
        REFERENCE_SNAPSHOT_PATH: render_reference_snapshot(reference),
    }


async def write() -> list[Path]:
    """Regenerate all outputs; returns the files that changed."""
    changed: list[Path] = []
    for path, content in (await render_all()).items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            changed.append(path)
    return changed


async def check() -> list[Path]:
    """Files whose content differs from what the code would generate."""
    return [
        path
        for path, content in (await render_all()).items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
